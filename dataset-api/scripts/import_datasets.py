def get_or_create_collection(
    db: Session, slug: str = "hifld", name: str = "HIFLD"
) -> Collection:
    """Get or create a collection."""
    statement = select(Collection).where(Collection.slug == slug)
    collection = db.exec(statement).first()

    if not collection:
        collection = Collection(
            slug=slug,
            name=name,
            description="HIFLD (Homeland Infrastructure Foundation-Level Data) datasets",
        )
        db.add(collection)
        db.commit()
        db.refresh(collection)
        logger.info(f"Created collection '{name}' (ID: {collection.id})")
    else:
        logger.info(f"Using existing collection '{name}' (ID: {collection.id})")

    return collection


def get_storage_location(db: Session, name: str) -> Optional[StorageLocation]:
    """Get a storage location by name (case-insensitive)."""
    # Try exact match first
    statement = select(StorageLocation).where(StorageLocation.name == name)
    result = db.exec(statement).first()
    if result:
        return result
    # Try case-insensitive match
    from sqlalchemy import func

    statement = select(StorageLocation).where(
        func.upper(StorageLocation.name) == name.upper()
    )
    return db.exec(statement).first()


def get_format(db: Session, format_type: str) -> Optional[Format]:
    """Get a format by type."""
    statement = select(Format).where(Format.format_type == format_type)
    return db.exec(statement).first()


async def resolve_first_chunk_file(glob_pattern: str, storage_client) -> Optional[str]:
    """
    Resolve a glob pattern to the first actual file path.

    For SeaweedFS (HTTP URLs), GeoServer doesn't support glob patterns,
    so we need to find the first actual file from the pattern.

    Args:
        glob_pattern: Glob pattern path (e.g., "dataset/file-*.zstd.parquet")
        storage_client: Storage client instance to use for file listing

    Returns:
        Path to the first file matching the pattern, or None if not found
    """
    if "*" not in glob_pattern:
        # Not a glob pattern, return as-is
        return glob_pattern

    # Extract directory and filename pattern
    # Pattern format: "dataset/file-*.zstd.parquet" or "dataset/file-*.parquet"
    path_parts = glob_pattern.rsplit("/", 1)
    if len(path_parts) == 2:
        directory = path_parts[0] + "/"
        filename_pattern = path_parts[1]
    else:
        directory = ""
        filename_pattern = glob_pattern

    # Try to list files first
    try:
        all_files = await storage_client.list_files(directory)

        # Convert glob pattern to regex for matching
        # Replace * with .* for regex matching
        pattern_regex = filename_pattern.replace("*", ".*")
        pattern_regex = f"^{re.escape(pattern_regex).replace('\\*', '.*')}$"

        # Find matching files
        matching_files = [
            f for f in all_files if re.match(pattern_regex, f.rsplit("/", 1)[-1])
        ]

        if matching_files:
            # Sort to get consistent ordering (first chunk should be file-0, file-1, etc.)
            matching_files.sort()
            first_file = matching_files[0]

            # If the file path doesn't include the directory, prepend it
            if directory and not first_file.startswith(directory):
                first_file = directory + first_file

            logger.info(
                f"Resolved glob pattern '{glob_pattern}' to first file: '{first_file}'"
            )
            return first_file
    except Exception as e:
        logger.debug(f"Error listing files for glob resolution: {e}")

    # If listing failed, try checking for common chunk patterns directly
    # For patterns like "file-*.zstd.parquet", try "file-0.zstd.parquet", "file-1.zstd.parquet", etc.
    base_name = (
        filename_pattern.replace("*", "")
        .replace(".zstd.parquet", "")
        .replace(".parquet", "")
    )
    if base_name.endswith("-"):
        base_name = base_name[:-1]

    # Try common chunk suffixes
    chunk_suffixes = ["-0.zstd.parquet", "-0.parquet", ".zstd.parquet", ".parquet"]
    for suffix in chunk_suffixes:
        test_path = directory + base_name + suffix
        try:
            if await storage_client.file_exists(test_path):
                logger.info(
                    f"Resolved glob pattern '{glob_pattern}' to first file: '{test_path}' (via direct check)"
                )
                return test_path
        except Exception:
            continue

    logger.warning(f"No files found matching pattern '{glob_pattern}'")
    return None


async def import_dataset(
    db: Session,
    dataset_entry: Dict[str, Any],
    collection: Collection,
    geoserver_storage_location: Optional[StorageLocation],
    geoserver_client: GeoServerClient,
    dry_run: bool = False,
    skip_existing: bool = False,
    upsert: bool = False,
) -> Dict[str, Any]:
    """Import a single dataset from JSONL entry."""
    dataset_slug = dataset_entry["slug"]
    dataset_name = dataset_entry["name"]
    dataset_description = dataset_entry.get("description", "")
    dataset_tags = dataset_entry.get("tags", {})
    import_settings = dataset_entry.get("import", {})
    files_data = dataset_entry.get("files", [])

    # Check if dataset already exists
    statement = select(Dataset).where(Dataset.slug == dataset_slug)
    existing_dataset = db.exec(statement).first()

    if existing_dataset:
        if skip_existing:
            logger.info(f"  → Dataset '{dataset_slug}' already exists, skipping...")
            return {"skipped": True, "dataset_id": existing_dataset.id}
        elif upsert:
            logger.info(
                f"  → Dataset '{dataset_slug}' already exists, deleting for reimport (upsert)..."
            )
            # Cascade deletes will handle File -> FileFormat -> FileSource deletion
            db.delete(existing_dataset)
            db.commit()
            # Ensure the session is cleared of the deleted object's state
            db.expire_all()
        else:
            raise Exception(
                f"Dataset '{dataset_slug}' already exists. Use --skip-existing to skip or --upsert to re-import."
            )

    if dry_run:
        logger.info(f"  [DRY RUN] Would create dataset: {dataset_slug}")
        logger.info(f"    Files: {len(files_data)}")
        return {"dry_run": True}

    # Create dataset
    dataset = Dataset(
        slug=dataset_slug,
        name=dataset_name,
        description=dataset_description,
        collection_id=collection.id,
        tags=dataset_tags if dataset_tags else None,
    )
    db.add(dataset)
    db.commit()
    db.refresh(dataset)
    logger.info(f"  ✓ Created dataset '{dataset_slug}' (ID: {dataset.id})")

    # Process files
    # Create one File entry per logical file from the JSONL
    # Each File can have multiple formats, and each format can have multiple sources
    # Note: GeoServer format/source entries will be created after successful GeoServer registration

    for file_data in files_data:
        file_name = file_data["name"]
        file_slug = file_data["slug"]
        file_description = file_data.get("description")
        layer_name = file_data.get("layer_name")
        source_file_path = file_data.get("source_file_path")
        file_metadata = file_data.get("file_metadata")

        # Create one File entry per logical file
        file_obj = File(
            dataset_id=dataset.id,
            name=file_name,
            slug=file_slug,
            description=file_description,
            layer_name=layer_name,
            source_file_path=source_file_path,
            file_metadata=(
                SpatialDatasetFileMetadata(**file_metadata) if file_metadata else None
            ),
        )
        db.add(file_obj)
        db.commit()
        db.refresh(file_obj)
        logger.info(f"    ✓ Created file '{file_obj.slug}' (ID: {file_obj.id})")

        # Process formats for this file
        # Skip GeoServer format - we'll create it after successful GeoServer registration
        formats_data = file_data.get("formats", [])

        for format_data in formats_data:
            format_type = format_data["format_type"]

            # Skip GeoServer format - will be created after successful registration
            if format_type == "geoserver":
                continue

            sources_data = format_data.get("sources", [])

            # Get format
            format_obj = get_format(db, format_type)
            if not format_obj:
                logger.warning(f"    ⚠ Format '{format_type}' not found, skipping...")
                continue

            # Create FileFormat (one per format type for this file)
            file_format = FileFormat(
                file_id=file_obj.id,
                format_id=format_obj.id,
            )
            db.add(file_format)
            db.commit()
            db.refresh(file_format)
            logger.info(
                f"      ✓ Created format '{format_type}' (ID: {file_format.id})"
            )

            # Process all sources for this format
            for source_data in sources_data:
                storage_location_name = source_data["storage_location_name"]

                # Get storage location
                storage_location = get_storage_location(db, storage_location_name)
                if not storage_location:
                    logger.warning(
                        f"        ⚠ Storage location '{storage_location_name}' not found, skipping..."
                    )
                    continue

                version = source_data.get("version", "2026-02-05")
                source_type = source_data["source_type"]
                location_data = source_data["location"]
                references_source_id = source_data.get("references_source_id")
                source_metadata = source_data.get("source_metadata")

                # Create FileSource - convert location_data to appropriate Pydantic model
                if source_type == "file":
                    location_obj = FileLocation(**location_data)
                elif source_type == "geoserver":
                    location_obj = GeoServerLocation(**location_data)
                else:
                    # For other types, use the dict directly (will be validated)
                    location_obj = location_data

                file_source = FileSource(
                    file_format_id=file_format.id,
                    storage_location_id=storage_location.id,
                    version=version,
                    source_type=source_type,
                    location=location_obj,
                    references_source_id=references_source_id,
                    source_metadata=(
                        SpatialDatasetFileMetadata(**source_metadata)
                        if source_metadata
                        else None
                    ),
                )
                db.add(file_source)
                db.commit()
                db.refresh(file_source)
                logger.info(f"        ✓ Created source (ID: {file_source.id})")

    # Register with GeoServer if requested
    # Create one store+layer per File entry (not per dataset)
    if import_settings.get("add_to_geoserver", True) and geoserver_storage_location:
        logger.info("  → Registering files with GeoServer...")

        # Process each file entry separately
        for file_data in files_data:
            file_slug = file_data["slug"]
            file_name = file_data["name"]

            # Find GeoParquet sources from the specified storage location for this file
            geoparquet_sources = []
            geoserver_loc_name_upper = geoserver_storage_location.name.upper()
            for format_data in file_data.get("formats", []):
                if format_data["format_type"] == "geoparquet":
                    for source_data in format_data.get("sources", []):
                        # Case-insensitive comparison
                        if (
                            source_data["storage_location_name"].upper()
                            == geoserver_loc_name_upper
                        ):
                            geoparquet_sources.append(source_data)

            if not geoparquet_sources:
                logger.info(
                    f"    ⚠ No GeoParquet sources found for file '{file_slug}' in '{geoserver_storage_location.name}', skipping..."
                )
                continue

            # For HTTP URLs (SeaweedFS), GeoServer doesn't support glob patterns
            # Use the first geoparquet file (not glob pattern)
            geoparquet_source = geoparquet_sources[0]
            location_path = geoparquet_source["location"]["path"]

            # Get the storage location for the GeoParquet source
            geoparquet_storage = get_storage_location(
                db, geoparquet_source["storage_location_name"]
            )

            if not geoparquet_storage:
                logger.warning(
                    f"    ⚠ Storage location '{geoparquet_source['storage_location_name']}' not found, skipping GeoServer registration"
                )
                continue

            # Create storage client for this location
            from storage.storage_client import create_storage_client

            # Handle config that might be a dict (from database) or Pydantic model
            config = geoparquet_storage.config
            if isinstance(config, dict):
                # Convert dict to Pydantic model for type checking
                config_type = config.get("type")
                if config_type in ("s3", "gcs", "seaweedfs"):
                    config = BucketStorageLocationConfig(**config)
                else:
                    logger.warning(
                        f"    ⚠ Storage location '{geoparquet_storage.name}' is not a bucket storage (type: {config_type}), skipping"
                    )
                    continue
            elif not isinstance(config, BucketStorageLocationConfig):
                logger.warning(
                    f"    ⚠ Storage location '{geoparquet_storage.name}' is not a bucket storage, skipping"
                )
                continue

            bucket = config.bucket
            base_url = config.base_url
            config_type = config.type  # Get explicit type from config

            # Create appropriate storage client based on config type
            if config_type == "gcs":
                storage_client = create_storage_client(
                    storage_type="gcs", bucket=bucket
                )
            elif config_type == "seaweedfs":
                storage_client = create_storage_client(
                    storage_type="seaweedfs",
                    bucket=bucket,
                    filer_url=base_url,
                )
            elif config_type == "s3":
                raise ValueError(
                    f"Storage location '{geoparquet_storage.name}' has type='s3'. "
                    "Explicit storage types ('gcs' or 'seaweedfs') are required. "
                    "Update the storage location config to use 'gcs' or 'seaweedfs'."
                )
            else:
                raise ValueError(
                    f"Unknown storage type '{config_type}' for storage location '{geoparquet_storage.name}'. "
                    "Must be 'gcs' or 'seaweedfs'."
                )

            # Handle glob patterns based on storage type
            # GCS supports glob patterns in S3/GS URIs
            # SeaweedFS doesn't support globs, so we need to resolve to first file
            if "*" in location_path:
                if config_type == "gcs":
                    # GCS supports glob patterns, use storage URI format
                    geoparquet_uri = storage_client.path_to_storage_uri(location_path)
                    logger.info(
                        f"    File '{file_slug}': Using glob pattern URI: {geoparquet_uri}"
                    )
                elif config_type == "seaweedfs":
                    # SeaweedFS doesn't support globs, resolve to first file
                    resolved_path = await resolve_first_chunk_file(
                        location_path, storage_client
                    )
                    if resolved_path:
                        location_path = resolved_path
                        logger.info(
                            f"    Resolved glob pattern to first file: {location_path}"
                        )
                        # Use HTTP URL for SeaweedFS (no globs)
                        geoparquet_uri = storage_client.path_to_public_url(
                            location_path, for_docker=True
                        )
                        logger.info(
                            f"    File '{file_slug}': Using URL: {geoparquet_uri}"
                        )
                    else:
                        logger.warning(
                            f"    Could not resolve glob pattern '{location_path}', skipping GeoServer registration"
                        )
                        continue
                else:
                    raise ValueError(
                        f"Storage location '{geoparquet_storage.name}' has type='s3'. "
                        "Explicit storage types ('gcs' or 'seaweedfs') are required for glob pattern handling."
                    )
            else:
                # No glob pattern - use appropriate format based on storage type
                if config_type == "gcs":
                    # GCS: use S3 URI format for GeoServer (GeoServer supports S3 URIs for GCS)
                    geoparquet_uri = storage_client.path_to_s3_uri(location_path)
                    logger.info(
                        f"    File '{file_slug}': Using S3 URI: {geoparquet_uri}"
                    )
                elif config_type == "seaweedfs":
                    # SeaweedFS: use HTTP URL
                    geoparquet_uri = storage_client.path_to_public_url(
                        location_path, for_docker=True
                    )
                    logger.info(f"    File '{file_slug}': Using URL: {geoparquet_uri}")
                else:
                    raise ValueError(
                        f"Storage location '{geoparquet_storage.name}' has type='s3'. "
                        "Explicit storage types ('gcs' or 'seaweedfs') are required."
                    )

            # Get GeoServer settings - use file-specific names
            workspace = import_settings.get("geoserver_workspace") or "hifld"
            # Create unique store and layer names per file
            store_name = f"{dataset_slug}-{file_slug}-store"
            layer_name = f"{dataset_slug}-{file_slug}"

            # Create GeoServer store
            store_created = await geoserver_client.create_geoparquet_store(
                workspace=workspace,
                store_name=store_name,
                geoparquet_url=geoparquet_uri,
            )

            if store_created:
                # Publish layer
                layer_published = await geoserver_client.publish_layer(
                    workspace=workspace,
                    store_name=store_name,
                    layer_name=layer_name,
                )

                if layer_published:
                    logger.info(
                        f"    ✓ GeoServer registration successful for file '{file_slug}': {workspace}:{layer_name}"
                    )

                    # Only create DB entries after successful GeoServer registration
                    # Get GeoServer format and storage location
                    geoserver_format = get_format(db, "geoserver")
                    geoserver_storage_loc = get_storage_location(db, "GeoServer")

                    if geoserver_format and geoserver_storage_loc:
                        # Find the File object
                        file_obj = db.exec(
                            select(File).where(
                                File.dataset_id == dataset.id, File.slug == file_slug
                            )
                        ).first()

                        if file_obj:
                            # Create FileFormat for GeoServer
                            file_format = FileFormat(
                                file_id=file_obj.id,
                                format_id=geoserver_format.id,
                            )
                            db.add(file_format)
                            db.commit()
                            db.refresh(file_format)

                            # Create FileSource for GeoServer
                            geoserver_location = GeoServerLocation(
                                workspace=workspace,
                                store_name=store_name,
                                layer_name=layer_name,
                            )

                            file_source = FileSource(
                                file_format_id=file_format.id,
                                storage_location_id=geoserver_storage_loc.id,
                                version=date.today().isoformat(),
                                source_type="geoserver",
                                location=geoserver_location,
                                references_source_id=None,
                                source_metadata=None,
                            )
                            db.add(file_source)
                            db.commit()
                            db.refresh(file_source)
                            logger.info(
                                f"    ✓ Created GeoServer DB entry (ID: {file_source.id})"
                            )
                        else:
                            logger.warning(
                                f"    ⚠ File '{file_slug}' not found, cannot create GeoServer DB entry"
                            )
                    else:
                        logger.warning(
                            "    ⚠ GeoServer format or storage location not found, cannot create DB entry"
                        )
                else:
                    logger.warning(
                        f"    ⚠ GeoServer layer publishing failed for file '{file_slug}', not creating DB entry"
                    )
            else:
                logger.warning(
                    f"    ⚠ GeoServer store creation failed for file '{file_slug}', not creating DB entry"
                )

    return {
        "dataset_id": dataset.id,
        "name": dataset_slug,
    }


async def import_datasets(
    db: Session,
    datasets: List[Dict[str, Any]],
    collection: Collection,
    geoserver_storage_location: Optional[StorageLocation],
    geoserver_client: GeoServerClient,
    dry_run: bool = False,
    skip_existing: bool = False,
    upsert: bool = False,
) -> Dict[str, Any]:
    """Import datasets from JSONL."""
    results = {
        "success": 0,
        "skipped": 0,
        "failed": 0,
        "errors": [],
    }

    for i, dataset_entry in enumerate(datasets, 1):
        dataset_slug = dataset_entry.get("slug", "unknown")
        try:
            logger.info(f"[{i}/{len(datasets)}] Processing: {dataset_slug}")
            result = await import_dataset(
                db,
                dataset_entry,
                collection,
                geoserver_storage_location,
                geoserver_client,
                dry_run,
                skip_existing,
                upsert,
            )

            if result.get("skipped"):
                results["skipped"] += 1
            elif result.get("dry_run"):
                results["success"] += 1
            else:
                results["success"] += 1
                logger.info(f"  ✓ Success: Dataset ID {result.get('dataset_id')}")

        except Exception as e:
            results["failed"] += 1
            error_msg = f"{dataset_slug}: {str(e)}"
            results["errors"].append(error_msg)
            logger.error(f"  ✗ Failed: {error_msg}")
            db.rollback()
            continue

    return results


def load_datasets_jsonl(jsonl_path: str | Path) -> List[Dict[str, Any]]:
    """Load datasets from JSONL file (local path or GCS URL)."""
    # Handle GCS URLs
    if isinstance(jsonl_path, str) and jsonl_path.startswith("gs://"):
        try:
            from google.cloud import storage
        except ImportError:
            raise ImportError(
                "google-cloud-storage is required for GCS URLs. "
                "Install with: pip install google-cloud-storage"
            )

        # Parse gs://bucket/path
        path = jsonl_path[5:]  # Remove gs://
        parts = path.split("/", 1)
        bucket_name = parts[0]
        blob_path = parts[1] if len(parts) > 1 else ""

        # Initialize GCS client (uses default credentials)
        client = storage.Client()
        bucket = client.bucket(bucket_name)
        blob = bucket.blob(blob_path)

        # Check if blob exists
        if not blob.exists():
            raise FileNotFoundError(f"JSONL file not found in GCS: {jsonl_path}")

        # Download and parse JSONL
        content = blob.download_as_text()
        datasets = []
        for line in content.splitlines():
            if line.strip():
                datasets.append(json.loads(line))

        logger.info(f"Loaded {len(datasets)} datasets from GCS: {jsonl_path}")
        return datasets

    # Handle local file path
    path = Path(jsonl_path)
    if not path.exists():
        raise FileNotFoundError(f"JSONL file not found: {jsonl_path}")

    datasets = []
    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            if line.strip():
                datasets.append(json.loads(line))
    return datasets


async def main():
    """Main entry point."""
    parser = argparse.ArgumentParser(
        description="Import datasets from JSONL into the database and GeoServer"
    )
    parser.add_argument(
        "--input",
        type=str,
        required=True,
        help="Input JSONL file path (local path or GCS URL like gs://bucket/path)",
    )
    parser.add_argument(
        "--geoserver-storage-location",
        type=str,
        default=None,
        help="Storage location name to use for GeoServer GeoParquet sources (e.g., 'GCS drp-hifld-copy-formatted-49775666365')",
    )
    parser.add_argument(
        "--collection",
        type=str,
        default="hifld",
        help="Collection slug to use (default: hifld)",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Preview what would be imported without making changes",
    )
    parser.add_argument(
        "--skip-existing",
        action="store_true",
        help="Skip datasets that already exist in the database",
    )
    parser.add_argument(
        "--upsert",
        action="store_true",
        help="Delete and re-import datasets that already exist (upsert behavior)",
    )
    parser.add_argument(
        "-v",
        "--verbose",
        action="store_true",
        help="Enable verbose logging",
    )

    args = parser.parse_args()

    if args.verbose:
        logging.getLogger().setLevel(logging.DEBUG)

    # Load datasets (function handles both local paths and GCS URLs)
    logger.info(f"Loading datasets from {args.input}...")
    try:
        datasets = load_datasets_jsonl(args.input)
    except FileNotFoundError as e:
        logger.error(str(e))
        sys.exit(1)
    logger.info(f"Loaded {len(datasets)} datasets")

    # Get database session
    db = get_db_session()
    try:
        # Get or create collection
        collection = get_or_create_collection(db, slug=args.collection)

        # Get GeoServer storage location if specified
        geoserver_storage_location = None
        if args.geoserver_storage_location:
            geoserver_storage_location = get_storage_location(
                db, args.geoserver_storage_location
            )
            if not geoserver_storage_location:
                logger.error(
                    f"GeoServer storage location '{args.geoserver_storage_location}' not found"
                )
                logger.error("Run seed_storage.py first to create storage locations")
                sys.exit(1)
            logger.info(
                f"Using GeoServer storage location: {geoserver_storage_location.name}"
            )

        # Create GeoServer client
        geoserver_client = GeoServerClient()

        # Validate arguments
        if args.skip_existing and args.upsert:
            logger.error("Cannot use both --skip-existing and --upsert flags together")
            sys.exit(1)

        # Import datasets
        results = await import_datasets(
            db,
            datasets,
            collection,
            geoserver_storage_location,
            geoserver_client,
            dry_run=args.dry_run,
            skip_existing=args.skip_existing,
            upsert=args.upsert,
        )

        # Print summary
        print("\n" + "=" * 50)
        print("IMPORT SUMMARY")
        print("=" * 50)
        print(f"  Success: {results['success']}")
        print(f"  Skipped: {results['skipped']}")
        print(f"  Failed:  {results['failed']}")

        if results["errors"]:
            print("\nErrors:")
            for error in results["errors"][:10]:
                print(f"  - {error}")
            if len(results["errors"]) > 10:
                print(f"  ... and {len(results['errors']) - 10} more errors")

        print("=" * 50)

        if results["failed"] > 0:
            sys.exit(1)

    finally:
        db.close()


if __name__ == "__main__":
    asyncio.run(main())
